// Generates src/ui/theme/tokens.css from tokens.json (exported from the Figma "Asm8 tokens" collection).
// Run: node scripts/tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync('src/ui/theme/tokens.json', 'utf8'));
const cssName = (name) => '--' + name.replace('/', '-');
const block = (selector, i) =>
  `${selector} {\n${Object.entries(src.vars)
    .map(([name, values]) => `  ${cssName(name)}: ${values[i]};`)
    .join('\n')}\n}\n`;

let css = `/* Generated by scripts/tokens.mjs from tokens.json — do not edit by hand. */\n`;
css += block(`:root,\n:root[data-theme='${src.modes[0]}']`, 0);
src.modes.slice(1).forEach((mode, k) => {
  css += `\n` + block(`:root[data-theme='${mode}']`, k + 1);
});
writeFileSync('src/ui/theme/tokens.css', css);
console.log(`tokens.css: ${src.modes.length} themes × ${Object.keys(src.vars).length} tokens`);
